def build_dataset():
    intents_list = []
    for intent, examples in INTENTS.items():
        intents_list.append({"intent": intent, "examples": examples})

    data = {"intents": intents_list}

    os.makedirs("data", exist_ok=True)
    out_path = "data/intents_v2.json"
    with open(out_path, "w") as f:
        json.dump(data, f, indent=2)

    total = sum(len(v) for v in INTENTS.values())
    print(f"Saved {out_path}")
    print(f"Total: {total} examples across {len(INTENTS)} intents")
    print(f"Avg per intent: {total/len(INTENTS):.1f}")


if __name__ == "__main__":
    build_dataset()
